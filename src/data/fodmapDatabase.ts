/** Build a quick lookup of normalized alias → entry */
export function buildAliasIndex(): Map<string, FodmapEntry> {
  const map = new Map<string, FodmapEntry>();
  for (const entry of FODMAP_DB) {
    const keys = [entry.name, ...entry.aliases];
    for (const k of keys) {
      map.set(normalizeKey(k), entry);
    }
  }
  return map;
}

export function normalizeKey(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s%-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
